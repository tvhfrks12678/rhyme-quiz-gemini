/**
 * Extracts vowels from Japanese Hiragana text.
 * Simple mapping for standard characters.
 */
export function extractVowels(text: string): string {
  const mapping: Record<string, string> = {
    // a
    か: "あ", さ: "あ", た: "あ", な: "あ", は: "あ", ま: "あ", や: "あ", ら: "あ", わ: "あ",
    が: "あ", ざ: "あ", だ: "あ", ば: "あ", ぱ: "あ", ぁ: "あ", ゃ: "あ",
    // i
    き: "い", し: "い", ち: "い", に: "い", ひ: "い", み: "い", り: "い",
    ぎ: "い", じ: "い", ぢ: "い", び: "い", ぴ: "い", ぃ: "い",
    // u
    く: "う", す: "う", つ: "う", ぬ: "う", ふ: "う", む: "う", ゆ: "う", る: "う",
    ぐ: "う", ず: "う", づ: "う", ぶ: "う", ぷ: "う", ぅ: "う", ゅ: "う",
    // e
    け: "え", せ: "え", て: "え", ね: "え", へ: "え", め: "え", れ: "え",
    げ: "え", ぜ: "え", で: "え", べ: "え", ぺ: "え", ぇ: "え",
    // o
    こ: "お", そ: "お", と: "お", の: "お", ほ: "お", も: "お", よ: "お", ろ: "お",
    ご: "お", ぞ: "お", ど: "お", ぼ: "お", ぽ: "お", ぉ: "お", ょ: "お",
    // vowels themselves
    あ: "あ", い: "い", う: "う", え: "え", お: "お",
    // special
    ん: "ん", っ: "っ", ー: "ー",
  };

  return text
    .split("")
    .map((char) => mapping[char] || "")
    .join("");
}
